import { copyFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const bindingsDir = resolve(root, 'crates/bindings')

// Read all .ts files from the single bindings directory
const files = existsSync(bindingsDir) ? readdirSync(bindingsDir).filter((f) => f.endsWith('.ts')).sort() : []

// Bundle into single types.d.ts
const lines = ['// Auto-generated by ts-rs. Do not edit manually.', '']

for (const file of files) {
  const content = readFileSync(resolve(bindingsDir, file), 'utf-8')
  for (const line of content.split('\n')) {
    if (line.startsWith('//') || line.startsWith('import ') || line.trim() === '') continue
    lines.push(line)
  }
  lines.push('')
}

writeFileSync(resolve(root, 'types.d.ts'), lines.join('\n'))

// Copy napi-generated .node binary and index.d.ts to root
const napiDir = resolve(root, 'crates/napi')
if (existsSync(napiDir)) {
  for (const file of readdirSync(napiDir)) {
    if (file.endsWith('.node')) {
      copyFileSync(resolve(napiDir, file), resolve(root, file))
    }
  }
  const napiDts = resolve(napiDir, 'index.d.ts')
  if (existsSync(napiDts)) {
    const napiContent = readFileSync(napiDts, 'utf-8')
    const napiLines = napiContent.split('\n')
    const funcLines = napiLines.filter((l) => l.startsWith('export declare'))

    // Extract interface blocks (e.g., export interface SourceEntry { ... })
    const interfaceBlocks = []
    let inBlock = false
    let block = []
    for (const line of napiLines) {
      if (line.startsWith('export interface')) {
        inBlock = true
        block = [line]
      } else if (inBlock) {
        block.push(line)
        if (line.trimEnd() === '}') {
          interfaceBlocks.push(...block)
          inBlock = false
          block = []
        }
      }
    }

    // Batch result types referenced by ts_return_type but not generated by NAPI-RS
    const batchResultTypes = [
      "export type BatchParseResult = { success: true; result: CstNode } | { success: false; error: string }",
      '',
      "export type BatchLowerResult = { success: true; result: IrModule } | { success: false; error: string }",
    ]

    const indexLines = [
      '/* eslint-disable */',
      "import type { CstNode, IrModule } from './types'",
      "export * from './types'",
      '',
      ...interfaceBlocks,
      ...(interfaceBlocks.length > 0 ? [''] : []),
      ...batchResultTypes,
      '',
      ...funcLines,
      '',
    ]
    writeFileSync(resolve(root, 'index.d.ts'), indexLines.join('\n'))
  }
}
